/**
 * Builds docs/TRACEABILITY.md: which automated tests cover which requirement.
 * Requirements live in docs/REQUIREMENTS.md as table rows starting with "| REQ-xxx |".
 * Tests declare coverage with Playwright tags: test('…', { tag: ['@REQ-009'] }, …).
 *
 *   npx tsx scripts/traceability.ts          # write the matrix
 *   npx tsx scripts/traceability.ts --check  # exit 1 if a requirement has no test (CI gate)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const check = process.argv.includes('--check');

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.spec\.ts$/.test(name)) out.push(p);
  }
  return out;
}

interface TestRef {
  title: string;
  file: string;
  line: number;
  tags: string[];
  project: string;
}

const files = walk(path.join(root, 'e2e', 'tests'));
const tests: TestRef[] = [];
const testRe =
  /test\(\s*(['"`])((?:\\.|(?!\1).)*)\1\s*,\s*\{\s*tag:\s*(\[[^\]]*\]|'[^']*'|"[^"]*")/g;
for (const file of files) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(testRe)) {
    const title = m[2]!;
    const tags = [...m[3]!.matchAll(/@[\w-]+/g)].map((t) => t[0]);
    const line = src.slice(0, m.index).split('\n').length;
    const rel = path.relative(root, file).replace(/\\/g, '/');
    tests.push({ title, file: rel, line, tags, project: rel.split('/')[2] ?? '' });
  }
}

const reqDoc = readFileSync(path.join(root, 'docs', 'REQUIREMENTS.md'), 'utf8');
const requirements = [...reqDoc.matchAll(/^\|\s*(REQ-\d{3})\s*\|\s*([^|]+?)\s*\|/gm)].map((m) => ({
  id: m[1]!,
  title: m[2]!,
}));

const byReq = new Map<string, TestRef[]>();
for (const t of tests)
  for (const tag of t.tags)
    if (tag.startsWith('@REQ-')) byReq.set(tag.slice(1), [...(byReq.get(tag.slice(1)) ?? []), t]);

const uncovered = requirements.filter((r) => !byReq.get(r.id)?.length);
const unknownTags = [...byReq.keys()].filter((id) => !requirements.some((r) => r.id === id));

const lines: string[] = [];
lines.push(
  '# Traceability matrix',
  '',
  `Generated by \`npm run traceability\` on ${new Date().toISOString().slice(0, 10)}.`,
  '',
);
lines.push(
  `${requirements.length} requirements · ${tests.length} tagged tests · ${requirements.length - uncovered.length} requirements covered${uncovered.length ? ` · **${uncovered.length} uncovered**` : ''}`,
  '',
);
lines.push('| Requirement | Tests | Where |', '|---|---:|---|');
for (const r of requirements) {
  const refs = byReq.get(r.id) ?? [];
  const where = [...new Set(refs.map((t) => t.project))].sort().join(', ');
  lines.push(`| ${r.id} ${r.title} | ${refs.length} | ${where || '**none**'} |`);
}
lines.push('', '## Tests per requirement', '');
for (const r of requirements) {
  const refs = byReq.get(r.id) ?? [];
  lines.push(`### ${r.id} ${r.title}`, '');
  if (refs.length === 0) lines.push('_No automated test yet._', '');
  for (const t of refs) lines.push(`- ${t.title} — \`${t.file}:${t.line}\``);
  lines.push('');
}
if (unknownTags.length)
  lines.push('## Tags without a requirement', '', ...unknownTags.map((t) => `- ${t}`), '');

writeFileSync(path.join(root, 'docs', 'TRACEABILITY.md'), lines.join('\n'));
console.log(
  `traceability: ${tests.length} tagged tests, ${requirements.length} requirements, ${uncovered.length} uncovered${unknownTags.length ? `, ${unknownTags.length} unknown tags (${unknownTags.join(', ')})` : ''}`,
);
if (check && (uncovered.length || unknownTags.length)) {
  for (const r of uncovered) console.error(`  uncovered: ${r.id} ${r.title}`);
  process.exit(1);
}
